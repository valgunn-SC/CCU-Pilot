const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const {DOMParser} = require('/opt/oai-docgen/node_modules/@xmldom/xmldom');
const sandbox = {window:{},DOMParser,DecompressionStream,TextDecoder,Blob,Response,Uint8Array,DataView,console};
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(require('path').join(__dirname,'..','xlsx-lite.js'),'utf8'),sandbox);
const buffer=fs.readFileSync('/home/oai/share/Optimisation_chaines_CCU.xlsx');
const file={arrayBuffer:async()=>buffer.buffer.slice(buffer.byteOffset,buffer.byteOffset+buffer.byteLength)};
(async()=>{
 const wb=await sandbox.window.XLSXLite.read(file);
 assert.ok(wb.SheetNames.includes('Flotte_Tokens'));
 assert.ok(wb.SheetNames.includes('Inventaire_CCU'));
 const tokens=wb.Sheets['Flotte_Tokens'];
 const ccus=wb.Sheets['Inventaire_CCU'];
 assert.strictEqual(tokens[4][1],'ATLS');
 assert.strictEqual(tokens[4][2],40);
 assert.strictEqual(ccus[4][1],'Golem OX');
 assert.strictEqual(ccus[12][2],'Railen');
 console.log('OK — import XLSX réel :',wb.SheetNames.length,'onglets lus');
})().catch(e=>{console.error(e);process.exit(1)});
